"""Generate rtl/ppu_2c02_rgb.sv: the 2C02's 512 colours (64 colours, each with
8 emphasis settings) as 24-bit RGB, by simulating its composite signal and
decoding it as an NTSC TV would.

The 2C02 makes each colour as a square wave between two voltage levels, high
for 6 of the 12 phases of the colour subcarrier; the colour's hue (its low 4
bits) picks which 6, and its luma (bits 5-4) picks the levels. Hue 0 is the
high level throughout, hues 13-15 the low level. Each emphasis bit attenuates
the signal during the 6 phases of one hue (red 12, green 4, blue 8), except on
hues 14 and 15. The levels are the NESdev wiki's measurements of a 2C02's
output into 75 ohms.

The TV takes luma as the signal's average and chroma from its fundamental,
relative to the colour burst (hue 8's phase), then converts YIQ to RGB. The
saturation and gamma are the usual settings of NES palette generators.

usage: gen_rgb.py [--check] [--png PATH]
  writes the RTL; --check instead fails if the RTL differs from what it would
  write; --png also draws the palette.
"""

import argparse
import math
import pathlib
import zlib

LOW = [0.228, 0.312, 0.552, 0.880]    # volts, by luma
HIGH = [0.616, 0.840, 1.100, 1.100]
ATTENUATE = 0.746
BLACK, WHITE = LOW[1], HIGH[3]        # $1D and $20
SATURATION = 0.8
GAMMA = 2.2 / 1.8                     # a CRT's gamma against the 1.8 the levels assume
HUE_SHIFT = -15.0                     # degrees; TVs' usual hue setting for the NES
PHASE0 = 123.0                        # degrees


def in_phase(hue, phase):
    return (hue + phase) % 12 < 6


def rgb(index):
    hue, luma, emph = index & 0x0F, (index >> 4) & 3, index >> 6
    if hue >= 14:
        luma = 1
    lo, hi = LOW[luma], HIGH[luma]
    if hue == 0:
        lo = hi
    if hue >= 13:
        hi = lo
    y = i = q = 0.0
    for p in range(12):
        v = hi if in_phase(hue, p) else lo
        if hue < 14 and ((emph & 1 and in_phase(12, p)) or (emph & 2 and in_phase(4, p))
                         or (emph & 4 and in_phase(8, p))):
            v *= ATTENUATE
        v = (v - BLACK) / (WHITE - BLACK)
        # Phase p's centre is (p + 0.5) twelfths of a subcarrier cycle in.
        # PHASE0 turns the I/Q plane so each hue lands where a TV shows it,
        # set against the colours everyone knows: $16 red, $1A green, $12
        # blue, $28 yellow, $27 orange, $2C cyan.
        a = math.radians((p + 0.5) * 30.0 + PHASE0 + HUE_SHIFT)
        y += v
        i += v * math.cos(a)
        q += v * math.sin(a)
    y /= 12
    i *= 2 * SATURATION / 12
    q *= 2 * SATURATION / 12
    r = y + 0.956 * i + 0.621 * q
    g = y - 0.272 * i - 0.647 * q
    b = y - 1.106 * i + 1.703 * q
    return tuple(round(max(0.0, min(1.0, c)) ** GAMMA * 255) for c in (r, g, b))


def sv(colours):
    lines = [
        "// SPDX-License-Identifier: Apache-2.0",
        "// Generated by tools/gen_rgb.py; edit that, not this.",
        "// The 2C02's colours as 24-bit RGB: `pix` is the PPU's {emphasis blue,",
        "// green, red, colour}, `rgb` {red, green, blue}, registered.",
        "module ppu_2c02_rgb (",
        "    input  logic        clk,",
        "    input  logic [8:0]  pix,",
        "    output logic [23:0] rgb",
        ");",
        "    always_ff @(posedge clk)",
        "        unique case (pix)",
    ]
    for n, (r, g, b) in enumerate(colours):
        lines.append(f"            9'h{n:03x}: rgb <= 24'h{r:02x}{g:02x}{b:02x};")
    lines += ["        endcase", "endmodule", ""]
    return "\n".join(lines)


def png(path, colours):
    # 16 colours a row, 32 rows (4 lumas x 8 emphasis settings), 16x16 swatches.
    w, h = 16 * 16, 32 * 16
    rows = []
    for y in range(h):
        row = bytearray([0])
        cy = y // 16
        for x in range(w):
            n = (cy // 4) * 64 + (cy % 4) * 16 + x // 16
            row += bytes(colours[n])
        rows.append(bytes(row))
    def chunk(t, d):
        return len(d).to_bytes(4, "big") + t + d + zlib.crc32(t + d).to_bytes(4, "big")
    data = b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", w.to_bytes(4, "big") + h.to_bytes(4, "big") + b"\x08\x02\x00\x00\x00")
    data += chunk(b"IDAT", zlib.compress(b"".join(rows))) + chunk(b"IEND", b"")
    pathlib.Path(path).write_bytes(data)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--png")
    args = ap.parse_args()
    colours = [rgb(n) for n in range(512)]
    out = pathlib.Path(__file__).resolve().parent.parent / "rtl" / "ppu_2c02_rgb.sv"
    if args.check:
        if out.read_text() != sv(colours):
            raise SystemExit(f"{out} is out of date: run {__file__}")
    else:
        out.write_text(sv(colours))
    if args.png:
        png(args.png, colours)


if __name__ == "__main__":
    main()
