"""Generate rtl/paddles_rate.sv: each paddle position's charge rate, the dump's
rate and the TIA's threshold, from the console's paddle circuit as Stella 7.0
models it (its AnalogReadout).

Each paddle input is a 68 nF capacitor, charged from 5 V through the paddle's
pot (0 to 1 Mohm) and 1.8 kohm, and dumped to ground through 50 ohm while
VBLANK bit 7 is set. The TIA reads it as 1 once it's above the voltage a pot of
1 Mohm reaches 379 lines after a dump. Time is counted in colour clocks at
Stella's rate, 60 x 228 x 262 a second.

Position p (0-255) is a pot of p / 256 Mohm, as Stella's paddles are at
multiples of 1/4096 of 1 Mohm (its default, the middle, is p = 128). Over one
colour clock a capacitor at u (a fraction of 5 V) goes to

  charging: u + (1 - u) * c,  c = 1 - exp(-1 / (R C f))
  dumped:   u - u * c_dump,   c_dump = 1 - exp(-1 / (50 C f))

Each c is m * 2^-(24 + s): a 24-bit mantissa m (top bit set) and a shift s.
The threshold is a 40-bit fraction of 5 V: the capacitor reads 1 when its own
40-bit u is greater.

usage: gen_rate.py [--check]
  writes the RTL; --check instead fails if the RTL differs from what it would write.
"""

import argparse
import math
import pathlib
import sys

R0 = 1.8e3
C = 68e-9
R_POT = 1e6
R_DUMP = 50
F = 60 * 228 * 262
TRIP_LINES = 379
U_BITS = 40


def rate(r):
    """(s, m) with m * 2^-(24 + s) = 1 - exp(-1 / (r C F)), m rounded to 24 bits."""
    c = -math.expm1(-1 / (r * C * F))
    s = 0
    while c * 2 ** (s + 1) < 1:
        s += 1
    m = round(c * 2 ** (24 + s))
    if m == 1 << 24:  # rounding carried out of the mantissa
        s, m = s - 1, 1 << 23
    assert (1 << 23) <= m < (1 << 24) and 0 <= s < 32
    return s, m


def threshold():
    u = -math.expm1(-TRIP_LINES * 228 / ((R_POT + R0) * C * F))
    return math.floor(u * 2**U_BITS)


def word(s, m):
    return f"29'h{(s << 24 | m):08x}"


def entry(s, m):
    """A ROM entry: s and m without its top bit, which is always set (Yosys's ROM inference
    leaves a bit that's the same in every entry undriven)."""
    return f"28'h{(s << 23 | (m & ((1 << 23) - 1))):07x}"


def rtl():
    entries = "\n".join(
        f"            8'd{p}: q <= {entry(*rate(R_POT * p / 256 + R0))};" for p in range(256)
    )
    return f"""// SPDX-License-Identifier: Apache-2.0
// Generated by tools/gen_rate.py; don't edit by hand.
// The paddle circuit's constants, as Stella 7.0 models it: `rate` is position
// `pos`'s charge rate (a pot of pos / 256 Mohm, 1.8 kohm and 68 nF), a block
// RAM ROM whose address is taken on the falling edge (on the GW2AR-18 a block
// RAM's address needs more hold than a short path from a register gives), read
// on the rising edge after; `dump_rate` is the dump's (50 ohm), and `uth` the
// TIA's threshold as a 40-bit fraction of 5 V. A rate is {{s[4:0], m[23:0]}}:
// m * 2^-(24 + s) of the way to its target each colour clock.
module paddles_rate (
    input  logic        clk,
    input  logic [7:0]  pos,
    output logic [28:0] rate,
    output logic [28:0] dump_rate,
    output logic [39:0] uth
);
    logic [7:0]  ix;
    logic [27:0] q;  // {{s, m[22:0]}}: m's top bit is always set

    always_ff @(negedge clk)
        ix <= pos;

    always_ff @(posedge clk)
        unique case (ix)
{entries}
        endcase

    assign rate      = {{q[27:23], 1'b1, q[22:0]}};
    assign dump_rate = {word(*rate(R_DUMP))};
    assign uth       = 40'h{threshold():010x};
endmodule
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    out = pathlib.Path(__file__).resolve().parent.parent / "rtl" / "paddles_rate.sv"
    text = rtl()
    if args.check:
        if out.read_text() != text:
            print(f"{out} differs from what gen_rate.py writes", file=sys.stderr)
            sys.exit(1)
        return
    out.write_text(text)


if __name__ == "__main__":
    main()
