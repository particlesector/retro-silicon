"""Generate rtl/apu_mixer.sv: the 2A03's nonlinear mix of its channels, as the
NESdev wiki gives it, in two tables (the larger a block RAM ROM).

The two pulse channels share one output and the triangle, noise and DMC
another, each a resistor network whose level isn't the sum of its inputs:

  pulse = 95.52 / (8128 / (p1 + p2) + 100)
  tnd   = 163.67 / (24329 / (3t + 2n + d) + 100)

(the second being the wiki's close fit to 159.79 / (1 / (t/8227 + n/12241 +
d/22638) + 100)). Both are 0 for a zero input. Their sum, at most 1.0001, is
scaled so the output fills 16 bits unsigned.

usage: gen_mixer.py [--check]
  writes the RTL; --check instead fails if the RTL differs from what it would write.
"""

import argparse
import pathlib
import sys

SCALE = 65520  # 1.0001 * 65520 < 65536


def pulse(n):
    return 0 if n == 0 else round(95.52 / (8128 / n + 100) * SCALE)


def tnd(n):
    return 0 if n == 0 else round(163.67 / (24329 / n + 100) * SCALE)


def rom(q, ix, f, count, width):
    lines = ["    always_ff @(posedge clk)", f"        unique case ({ix})"]
    for n in range(1 << width):
        lines.append(f"            {width}'d{n}: {q} <= 16'd{f(min(n, count - 1))};")
    lines.append("        endcase")
    return "\n".join(lines)


def func(name, f, count, width):
    lines = [f"    function automatic logic [15:0] {name}(input logic [{width - 1}:0] i);", "        case (i)"]
    for n in range(count):
        lines.append(f"            {width}'d{n}: {name} = 16'd{f(n)};")
    lines += [f"            default: {name} = 16'd{f(count - 1)};", "        endcase", "    endfunction"]
    return "\n".join(lines)


def rtl():
    return f"""// SPDX-License-Identifier: Apache-2.0
// Generated by tools/gen_mixer.py; don't edit by hand.
// The 2A03's nonlinear mix of its five channels (the NESdev wiki's formulas),
// from two tables: out is 16 bits unsigned, 0 for silence. The indexes are
// taken on the falling edge after the levels change; the larger table is a
// block RAM ROM read on the rising edge after that, so out follows the levels
// by one to two clocks: give it two after a change. (On the GW2AR-18 a block
// RAM's address needs more hold than a short path from a register gives.)
module apu_mixer (
    input  logic        clk,
    input  logic [3:0]  pulse1,
    input  logic [3:0]  pulse2,
    input  logic [3:0]  triangle,
    input  logic [3:0]  noise,
    input  logic [6:0]  dmc,
    output logic [15:0] out
);
    logic [4:0]  p_ix;
    logic [7:0]  t_ix;
    logic [15:0] t_q;

    always_ff @(negedge clk) begin
        p_ix <= 5'(pulse1) + 5'(pulse2);
        t_ix <= 8'(3 * triangle) + 8'(2 * noise) + 8'(dmc);
    end

{func("pulse_of", pulse, 31, 5)}

{rom("t_q", "t_ix", tnd, 203, 8)}

    assign out = pulse_of(p_ix) + t_q;
endmodule
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    path = pathlib.Path(__file__).resolve().parents[1] / "rtl/apu_mixer.sv"
    want = rtl()
    if args.check:
        if path.read_text() != want:
            print(f"{path} differs from what gen_mixer.py writes", file=sys.stderr)
            return 1
        return 0
    path.write_text(want)
    return 0


if __name__ == "__main__":
    sys.exit(main())
