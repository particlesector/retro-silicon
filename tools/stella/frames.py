"""Golden frame CRCs for the Atari 2600's test cartridges, from Stella.

usage: tools/stella/frames.py [--roms DIR] [--out FILE] [--glitch-out FILE] [--audio-out FILE] [--stella-frames PATH] [--dump DIR]

For each cartridge in testroms/manifest-2600.toml with check = "frame", runs
it in Stella (tools/stella/stella-frames, default the one on PATH) for its
`frames` and writes one line to --out (default
harness/golden/a2600_frames_crc32.txt), in the format of
nes_frames_crc32.txt: id, frames ended, the last frame's CRC-32, check,
result, path. --dump also writes each frame's .tia and .ppm into DIR/<id>/.

A cartridge whose behaviour Stella gets wrong (where the TIA's die, from its transistor-level netlist,
and another emulator agree against it) carries `golden_crc`, the right frame's CRC, and `stella_crc`,
what Stella gives: its line takes `golden_crc`, once Stella is checked to still give `stella_crc`
(so a change in Stella can't hide behind the override). `golden_from` says where the frame came from.

A cartridge with `audio_samples` (N) also gets a line in harness/golden/a2600_audio_crc32.txt
(--audio-out): the CRC-32 of Stella's first N sound samples from power-up, each its two channel
sums (each channel's 4-bit level summed over the colour clocks since the last sample) as two
little-endian 16-bit words. Stella writes them where RS_STELLA_AUDIO says, which takes the rig's
Stella build (my-fpga-rig's tools/stella/audio.patch).

It also writes harness/golden/a2600_score_glitch_crc32.txt (--glitch-out), the frames with
video/tia's SCORE_GLITCH on: the same, but for a cartridge with `score_glitch_crc` (from
`score_glitch_from`), that frame.
"""

import argparse
import os
import subprocess
import sys
import tempfile
import tomllib
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def main():
    default_roms = os.environ.get("RS_TESTROMS", Path.home() / ".cache/retro-silicon/testroms")
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--roms", type=Path, default=Path(default_roms))
    parser.add_argument("--out", type=Path)
    parser.add_argument("--glitch-out", type=Path)
    parser.add_argument("--audio-out", type=Path)
    parser.add_argument("--stella-frames", default="stella-frames")
    parser.add_argument("--dump", type=Path)
    args = parser.parse_args()

    out_path = args.out or ROOT / "harness/golden/a2600_frames_crc32.txt"
    glitch_path = args.glitch_out or ROOT / "harness/golden/a2600_score_glitch_crc32.txt"
    audio_path = args.audio_out or ROOT / "harness/golden/a2600_audio_crc32.txt"
    audio = [
        "# Golden sound CRCs from Stella 7.0: id, samples, CRC-32 of their channel sums, path.",
        "# Each sample is its two channel sums (4-bit levels summed since the last sample) as two",
        "# little-endian 16-bit words, from power-up. Generated by tools/stella/frames.py; don't edit by hand.",
    ]
    tmp = tempfile.TemporaryDirectory()
    manifest = tomllib.loads((ROOT / "testroms/manifest-2600.toml").read_text())
    lines = [
        "# Golden frame CRCs from Stella 7.0: id, frames ended, CRC-32 of the last, check, result, path.",
        "# The frame is 160 x 228 TIA colour values from the 23rd line after VSYNC ends.",
        "# Generated by tools/stella/frames.py; don't edit by hand.",
    ]
    glitch = [
        "# Golden frame CRCs with video/tia's SCORE_GLITCH on: a2600_frames_crc32.txt's, but for the",
        "# cartridges that draw score mode's middle, whose frames come from score_glitch_from.",
        "# Generated by tools/stella/frames.py; don't edit by hand.",
    ]
    for rom in manifest["rom"]:
        if rom.get("check") != "frame":
            continue
        path = f"{rom['source']}/{rom['path']}"
        cmd = [args.stella_frames, "--rom", str(args.roms / path), "--frames", str(rom["frames"])]
        if args.dump:
            (args.dump / rom["id"]).mkdir(parents=True, exist_ok=True)
            cmd += ["--dump", str(args.dump / rom["id"])]
        env = dict(os.environ)
        log = Path(tmp.name) / "audio.bin"
        if "audio_samples" in rom:
            env["RS_STELLA_AUDIO"] = str(log)
        out = subprocess.run(cmd, check=True, capture_output=True, text=True, env=env).stdout.split()
        # stella-frames prints "<frame> <crc>"; Stella's own messages may come first.
        frame, crc = out[-2], out[-1]
        if int(frame) != rom["frames"]:
            sys.exit(f"frames: {rom['id']}: stella-frames gave frame {frame}")
        if "golden_crc" in rom:
            if int(crc, 16) != int(rom["stella_crc"], 16):
                sys.exit(f"frames: {rom['id']}: Stella gives 0x{crc}, not its stella_crc {rom['stella_crc']}")
            crc = f"{int(rom['golden_crc'], 16):08x}"
            lines.append(f"# {rom['id']}: not Stella's frame ({rom['stella_crc']}): {rom['golden_from']}")
        lines.append(f"{rom['id']} {rom['frames']} 0x{crc} frame - {path}")
        print(lines[-1])
        if "score_glitch_crc" in rom:
            crc = f"{int(rom['score_glitch_crc'], 16):08x}"
            glitch.append(f"# {rom['id']}: {rom['score_glitch_from']}")
        glitch.append(f"{rom['id']} {rom['frames']} 0x{crc} frame - {path}")
        if "audio_samples" in rom:
            n = rom["audio_samples"]
            data = log.read_bytes() if log.exists() else b""
            if len(data) < 4 * n:
                sys.exit(f"frames: {rom['id']}: Stella gave {len(data) // 4} sound samples, not {n} "
                         "(does its core have the rig's audio.patch?)")
            audio.append(f"{rom['id']} {n} 0x{zlib.crc32(data[:4 * n]):08x} {path}")
            print(audio[-1])
    out_path.write_text("\n".join(lines) + "\n")
    glitch_path.write_text("\n".join(glitch) + "\n")
    audio_path.write_text("\n".join(audio) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
