"""Writes systems/game-boy/rtl/gb_color.sv: the Game Boy Color's 15-bit colours to 24-bit RGB for
HDMI, corrected as SameBoy's "modern balanced" colour correction does (its default), from its
published formula (facts only; this is our own code):

- each 5-bit channel goes through a curve to 8 bits (the Color's LCD response);
- green becomes a mix of green and blue, ((g^1.6 * 3 + b^1.6) / 4)^(1/1.6), as the LCD's green
  sub-pixel shows some blue.

usage: tools/gb/color_table.py [--out PATH]
"""

import argparse
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CURVE = [0, 6, 12, 20, 28, 36, 45, 56, 66, 76, 88, 100, 113, 125, 137, 149, 161, 172, 182, 192, 202, 210,
         218, 225, 232, 238, 243, 247, 250, 252, 254, 255]
GAMMA = 1.6


def c_round(x: float) -> int:
    return int(math.floor(x + 0.5))  # C's round() for x >= 0


def green(g5: int, b5: int) -> int:
    g, b = CURVE[g5], CURVE[b5]
    if g == b:
        return g
    return c_round(pow((pow(g / 255.0, GAMMA) * 3 + pow(b / 255.0, GAMMA)) / 4, 1 / GAMMA) * 255)


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--out", type=Path, default=ROOT / "systems/game-boy/rtl/gb_color.sv")
    out = ap.parse_args().out
    lines = [
        "// SPDX-License-Identifier: Apache-2.0",
        "// Generated by tools/gb/color_table.py; don't edit by hand.",
        "//",
        "// The Game Boy Color's 15-bit colour (red in bits 4-0, green 9-5, blue 14-10) as 24-bit RGB,",
        "// corrected as SameBoy's \"modern balanced\" colour correction does: each channel through the",
        "// LCD's curve, and green mixed with some blue. Registered: `rgb` is `c`'s a clock later.",
        "module gb_color (",
        "    input  logic        clk,",
        "    input  logic [14:0] c,",
        "    output logic [23:0] rgb",
        ");",
        "    function automatic logic [7:0] curve(input logic [4:0] x);",
        "        case (x)",
    ]
    for i, v in enumerate(CURVE):
        lines.append(f"            5'd{i}: curve = 8'd{v};")
    lines += ["            default: curve = 8'd0;", "        endcase", "    endfunction", "",
              "    // green from green and blue",
              "    function automatic logic [7:0] mix(input logic [9:0] gb_);",
              "        case (gb_)"]
    for g in range(32):
        for b in range(32):
            lines.append(f"            10'd{b * 32 + g}: mix = 8'd{green(g, b)};")
    lines += ["            default: mix = 8'd0;", "        endcase", "    endfunction", "",
              "    always_ff @(posedge clk)",
              "        rgb <= {curve(c[4:0]), mix(c[14:5]), curve(c[14:10])};",
              "endmodule", ""]
    out.write_text("\n".join(lines))


if __name__ == "__main__":
    main()
