"""Golden frame CRCs from MesenCE for the Game Boy, and a check of each test ROM's result.

usage: tools/mesen/gb_frames.py [--mesen PATH] [--roms DIR] [--out FILE] [--home DIR]
                                [--only ID,...] [--jobs N]
       tools/mesen/gb_frames.py --dump ID FRAME [--mesen PATH] [--roms DIR] > frame.txt

For each ROM in testroms/manifest-gb.toml, runs it in MesenCE from power-up,
through SameBoy's boot ROM for its model (built by testroms/fetch.py: MesenCE
loads it from its Firmware folder in place of its own copy), until the ROM
reports its result, then MARGIN frames more, and records the CRC-32 of that
last frame in the core's pixel format: 2 bytes a pixel, low first, row by row,
160 x 144; on the Game Boy the pixel's shade (0 white to 3 black, after the
palette registers), on the Color its 15-bit colour as the palette RAM holds it
(red in bits 0-4, green 5-9, blue 10-14), before any colour correction.

The results, by the manifest's check:
  serial   blargg's: text over the serial port, ending in "Passed" or "Failed"
  blargg   blargg's newer ROMs: $80 at cartridge RAM $A000 while running, then
           the result (0 a pass), valid once $A001-$A003 hold DE B0 61
  mooneye  Mooneye's: 3 5 8 13 21 34 over the serial port for a pass, 42 (hex)
           six times for a failure
  frame    no result of its own; the frame `frames` is recorded

A ROM with `sav` (a file of battery RAM) powers up with it as its cartridge RAM,
and one with `again` runs twice, the second time from the battery RAM the first
left; either way, savcrc= is the CRC-32 of the cartridge RAM at the end, which a
board must end with too. A ROM with an `input` script (`frame:keys, ...`, gb_sys's keys byte held from
that frame on) gets those buttons through MesenCE's setInput.

Writes `id model frames crc32 check result path [input=...]` lines to --out
(default harness/golden/gb_frames_crc32.txt; with --only, just those ROMs'
lines, the others kept): frames is how many frames have ended at
the recorded one, result `pass`, `fail` (the ROM's code after a colon, if it
gives one), `none` or `-` for a frame check, path the ROM's under the
test-ROM directory, a space in it as %20. A ROM whose result MesenCE doesn't
give within its frame limit (twice the manifest's `frames`, at least 1200) is
an error, unless the manifest's `mesen` says MesenCE gives none: then the
frame at the limit is recorded, its result `none`. A ROM that fails in
MesenCE is recorded as it is, its result `fail`: the core must match it until
a second opinion shows MesenCE wrong: then the manifest's `override` gives
the right result and CRC (from SameBoy, a ROM that passes on the hardware it
was written for), applied only while MesenCE still gives the CRC it names
(`mesen`), so a MesenCE that changes is looked at again. The frames recorded are
checked against the manifest's: the result must come at the manifest's
`frames` (a frame check's frame is that).

MesenCE runs with its own settings, one home folder a job under --home
(default ~/.cache/retro-silicon/mesen-gb): the model the manifest gives (dmg,
the Game Boy; cgb, the Game Boy Color), colour correction and frame blending
off, and the Game Boy's shades as colours MesenCE gives back exactly. --dump
prints one frame as rows of hex values, for tools/frame.py.

Needs MesenCE and xvfb-run. Exit codes: 0 every ROM gave a result, 2 one
didn't, or a file is missing.
"""

import argparse
import concurrent.futures
import json
import os
import queue
import re
import shutil
import subprocess
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
MARGIN = 30     # frames after the ROM's result before the golden frame
MIN_LIMIT = 1200
MODELS = {"dmg": "Gameboy", "cgb": "GameboyColor"}
BOOT = {"dmg": "dmg_boot.bin", "cgb": "cgb_boot.bin"}  # in the boot ROMs' [[boot]] entries
# The Game Boy's shade s as a colour MesenCE gives back exactly: MesenCE keeps
# colours as 15-bit RGB, so s goes in blue's 5 bits.
SHADES = [s << 3 for s in range(4)]

LUA = """
-- SPDX-License-Identifier: Apache-2.0
-- Generated by tools/mesen/gb_frames.py.
local check, frames, limit, cgb, dump, savcrc = "{check}", {frames}, {limit}, {cgb}, {dump}, {savcrc}
local margin = {margin}
-- The input script: {{frame, keys}}, the keys as gb_sys's `keys` byte (bit 7 Start, Select, B, A,
-- Down, Up, Left, bit 0 Right), held from that frame on.
local script = {script}
local names = {{"right", "left", "up", "down", "a", "b", "select", "start"}}
local crc_table = {{}}
for i = 0, 255 do
  local c = i
  for _ = 1, 8 do
    if c & 1 == 1 then c = 0xEDB88320 ~ (c >> 1) else c = c >> 1 end
  end
  crc_table[i] = c
end
-- MesenCE's screen buffer holds each 5-bit channel as 8 bits, (c << 3) | (c >> 2).
local function pixel(v)
  local r, g, b = (v >> 19) & 0x1F, (v >> 11) & 0x1F, (v >> 3) & 0x1F
  if cgb then return r | (g << 5) | (b << 10) end
  return b
end
local serial, sb = {{}}, 0
emu.addMemoryCallback(function(addr, value)
  if addr == 0xFF01 then sb = value
  elseif (value & 0x81) == 0x81 then serial[#serial + 1] = sb end
end, emu.callbackType.write, 0xFF01, 0xFF02, emu.cpuType.gameboy, emu.memType.gameboyMemory)
local function text(bytes)
  local t = {{}}
  for i = 1, #bytes do t[i] = string.char(bytes[i]) end
  return table.concat(t)
end
local function cart_text()
  local t, a = {{}}, 4
  local n = emu.getMemorySize(emu.memType.gbCartRam)
  while a < n do
    local c = emu.read(a, emu.memType.gbCartRam)
    if c == 0 then break end
    t[#t + 1] = string.char(c)
    a = a + 1
  end
  return table.concat(t)
end
-- The ROM's result, once it has one: "pass", "fail" or "fail:<code>".
local function result()
  if check == "serial" then
    local s = text(serial)
    if s:find("Passed") then return "pass", s end
    if s:find("Failed") then return "fail", s end
  elseif check == "mooneye" then
    if #serial >= 6 then
      local pass = {{3, 5, 8, 13, 21, 34}}
      for i = 1, 6 do
        if serial[i] ~= pass[i] then return "fail", "" end
      end
      return "pass", ""
    end
  elseif check == "blargg" then
    if emu.getMemorySize(emu.memType.gbCartRam) >= 4 and emu.read(1, emu.memType.gbCartRam) == 0xDE
       and emu.read(2, emu.memType.gbCartRam) == 0xB0 and emu.read(3, emu.memType.gbCartRam) == 0x61 then
      local st = emu.read(0, emu.memType.gbCartRam)
      if st < 0x80 then return st == 0 and "pass" or ("fail:" .. st), cart_text() end
    end
  end
  return nil
end
local ended, want, done = 0, (check == "frame") and frames or -1, false
if #script > 0 then
  emu.addEventCallback(function()
    local k = 0
    for _, e in ipairs(script) do
      if e[1] <= ended then k = e[2] end
    end
    local t = {{}}
    for i = 1, 8 do t[names[i]] = (k >> (i - 1)) & 1 == 1 end
    emu.setInput(t, 0)
  end, emu.eventType.inputPolled)
end
emu.addEventCallback(function()
  if done then return end
  ended = ended + 1
  if want < 0 then
    local r, report = result()
    if r then
      print("result " .. r .. " " .. ended)
      if report and #report > 0 then print("report " .. report:gsub("\\n", "|")) end
      want = ended + margin
    elseif ended >= limit then
      print("timeout " .. ended .. " serial " .. text(serial):gsub("\\n", "|"))
      want = ended
    end
  end
  if ended ~= want then return end
  done = true
  local b = emu.getScreenBuffer()
  local c = 0xFFFFFFFF
  for i = 1, #b do
    local p = pixel(b[i])
    c = crc_table[(c ~ p) & 0xFF] ~ (c >> 8)
    c = crc_table[(c ~ (p >> 8)) & 0xFF] ~ (c >> 8)
  end
  print(string.format("crc %d %08x", ended, (~c) & 0xFFFFFFFF))
  if savcrc then
    -- The cartridge's RAM at the end: the battery RAM a board must end with too.
    local s = 0xFFFFFFFF
    for a = 0, emu.getMemorySize(emu.memType.gbCartRam) - 1 do
      s = crc_table[(s ~ emu.read(a, emu.memType.gbCartRam)) & 0xFF] ~ (s >> 8)
    end
    print(string.format("savcrc %08x", (~s) & 0xFFFFFFFF))
  end
  if dump then
    for y = 0, 143 do
      local row = {{}}
      for x = 0, 159 do row[#row + 1] = string.format("%04x", pixel(b[y * 160 + x + 1])) end
      print("row " .. y .. " " .. table.concat(row, " "))
    end
  end
  emu.stop(0)
end, emu.eventType.endFrame)
"""


def setup_home(home: Path, model: str, boot: dict):
    cfg = home / ".config" / "MesenCE"
    (cfg / "Firmware").mkdir(parents=True, exist_ok=True)
    gb = {"Model": MODELS[model], "GbcAdjustColors": False, "BlendFrames": False, "RamPowerOnState": "AllZeros",
          "BgColors": SHADES, "Obj0Colors": SHADES, "Obj1Colors": SHADES}
    (cfg / "settings.json").write_text(json.dumps({"Gameboy": gb}))
    for name, path in boot.items():
        shutil.copyfile(path, cfg / "Firmware" / name)
    # MesenCE keeps battery RAM between runs: start each from power-up.
    shutil.rmtree(cfg / "Saves", ignore_errors=True)


def parse_input(text: str):
    """A manifest `input` ("frame:keys,..."): [(frame, keys)], in order."""
    out = []
    for e in filter(None, (x.strip() for x in text.split(","))):
        f, k = e.split(":")
        out.append((int(f), int(k, 0)))
    if [f for f, _ in out] != sorted(f for f, _ in out) or any(not 0 <= k <= 255 for _, k in out):
        raise ValueError(f"bad input script {text!r}")
    return out


def run(mesen, home: Path, boot: dict, rom: dict, path: Path, dump=False, frames=None, sav: Path | None = None):
    """Runs one ROM; returns MesenCE's output. sav: the battery RAM to power up with; with the
    ROM's `again`, it runs twice, the second time from the battery RAM the first left. With
    either, the output has the cartridge RAM's CRC-32 at the end too ("savcrc")."""
    check = "frame" if frames is not None else rom["check"]
    want = frames if frames is not None else rom["frames"]
    limit = max(MIN_LIMIT, 2 * rom["frames"])
    setup_home(home, rom["model"], boot)
    lua = home / "gb_frames.lua"
    script = "{" + ", ".join(f"{{{f}, {k}}}" for f, k in parse_input(rom.get("input", ""))) + "}"
    again = rom.get("again", False)
    lua.write_text(LUA.format(check=check, frames=want, limit=limit, cgb="true" if rom["model"] == "cgb" else "false",
                              dump="true" if dump else "false", margin=MARGIN, script=script,
                              savcrc="true" if sav or again else "false"))
    # MesenCE keeps a Game Boy's battery RAM as Saves/<ROM's name>.srm, written as it stops.
    if sav:
        saves = home / ".config" / "MesenCE" / "Saves"
        saves.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(sav, saves / (path.stem + ".srm"))
    env = dict(os.environ, HOME=str(home))
    out = ""
    for _ in range(2 if again else 1):
        p = subprocess.run(["xvfb-run", "-a", mesen, "--testrunner", str(path), str(lua)],
                           capture_output=True, text=True, timeout=1800, env=env)
        out = p.stdout
    return out


def main():
    default_roms = os.environ.get("RS_TESTROMS", Path.home() / ".cache/retro-silicon/testroms")
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--mesen", default="Mesen")
    ap.add_argument("--roms", type=Path, default=Path(default_roms))
    ap.add_argument("--out", type=Path, default=ROOT / "harness/golden/gb_frames_crc32.txt")
    ap.add_argument("--home", type=Path, default=Path.home() / ".cache/retro-silicon/mesen-gb")
    ap.add_argument("--dump", nargs=2, metavar=("ID", "FRAME"))
    ap.add_argument("--only", help="comma-separated ROM ids")
    ap.add_argument("--jobs", type=int, default=min(8, os.cpu_count() or 1))
    args = ap.parse_args()
    only = set(args.only.split(",")) if args.only else None

    manifest = tomllib.loads((ROOT / "testroms/manifest-gb.toml").read_text())
    boot = {}
    for b in manifest["boot"]:
        path = args.roms / b["source"] / b["path"]
        if not path.exists():
            print(f"MISSING boot ROM {b['id']}: {path}; run testroms/fetch.py", file=sys.stderr)
            return 2
        boot[Path(b["path"]).name] = path
    if set(BOOT.values()) - set(boot):
        print(f"the manifest's [[boot]] entries must include {', '.join(BOOT.values())}", file=sys.stderr)
        return 2
    roms = {r["id"]: r for r in manifest["rom"]}

    if args.dump:
        rid, frame = args.dump
        r = roms[rid]
        out = run(args.mesen, args.home / "dump", boot, r, args.roms / r["source"] / r["path"], True, int(frame) + 1)
        for line in out.splitlines():
            if line.startswith("row "):
                print(line[4:].split(" ", 1)[1])
        return 0

    todo = [r for r in manifest["rom"] if only is None or r["id"] in only]
    homes = queue.Queue()
    for i in range(args.jobs):
        homes.put(args.home / f"job{i}")

    def one(r):
        path = args.roms / r["source"] / r["path"]
        if not path.exists():
            return r, None, f"MISSING {r['id']}: {path}; run testroms/fetch.py"
        home = homes.get()
        try:
            sav = args.roms / r["source"] / r["sav"]["path"] if "sav" in r else None
            return r, run(args.mesen, home, boot, r, path, sav=sav), None
        finally:
            homes.put(home)

    lines = {}
    worst = 0
    with concurrent.futures.ThreadPoolExecutor(args.jobs) as pool:
        for r, out, err in pool.map(one, todo):
            if err:
                print(err, file=sys.stderr)
                worst = 2
                continue
            crc = re.search(r"^crc (\d+) ([0-9a-f]{8})$", out, re.M)
            res = re.search(r"^result (\S+) (\d+)$", out, re.M)
            timeout = re.search(r"^timeout .*$", out, re.M)
            none = r.get("mesen", "").startswith("no result")
            if not crc or (r["check"] != "frame" and not res and not (timeout and none)):
                print(f"ERROR   {r['id']}: no result from MesenCE" + (f" ({timeout.group(0)})" if timeout else ""),
                      file=sys.stderr)
                worst = 2
                continue
            result = res.group(1) if res else "none" if timeout else "-"
            finish = f", finished at {res.group(2)}" if res else ""
            at = int(res.group(2)) if res else int(crc.group(1))
            if not timeout and at != r["frames"]:
                print(f"WARN    {r['id']}: {'finished' if res else 'recorded'} at {at}, the manifest says {r['frames']}",
                      file=sys.stderr)
            print(f"{'FAIL' if result.startswith('fail') else 'ok':7} {r['id']}: {result}{finish}, "
                  f"frame {int(crc.group(1)) - 1} 0x{crc.group(2)}")
            got = "0x" + crc.group(2)
            fix = r.get("override")
            if fix and fix["mesen"] == got:
                print(f"        {r['id']}: {fix['result']} {fix['crc']} in place of MesenCE's ({fix['why']})")
                result, got = fix["result"], fix["crc"]
            elif fix:
                print(f"WARN    {r['id']}: MesenCE gives {got}, not the {fix['mesen']} its override names; "
                      "the override isn't applied", file=sys.stderr)
            inp = r.get("input", "")
            lines[r["id"]] = (f"{r['id']} {r['model']} {crc.group(1)} {got} {r['check']} {result} "
                              f"{r['source']}/{r['path'].replace(' ', '%20')}" + (f" input={inp.replace(' ', '')}" if inp else ""))
            if "sav" in r:
                lines[r["id"]] += f" sav={r['source']}/{r['sav']['path']}"
            if r.get("again"):
                lines[r["id"]] += " again"
            sc = re.search(r"^savcrc ([0-9a-f]{8})$", out, re.M)
            if sc:
                lines[r["id"]] += f" savcrc=0x{sc.group(1)}"
    head = ["# Golden frame CRCs from MesenCE: id, model, frames ended, CRC-32 of the last, check, result, path,",
            "# and the input script (input=frame:keys,..., gb_sys's keys held from that frame on) if it has one.",
            "# Generated by tools/mesen/gb_frames.py; don't edit by hand."]
    if only is not None:
        # Just these ROMs' lines, the others kept as they were.
        old = {}
        if args.out.exists():
            for line in args.out.read_text().splitlines():
                if line and not line.startswith("#"):
                    old[line.split()[0]] = line
        old.update(lines)
        lines = old
    args.out.write_text("\n".join(head + [lines[r["id"]] for r in manifest["rom"] if r["id"] in lines]) + "\n")
    return worst


if __name__ == "__main__":
    sys.exit(main())
