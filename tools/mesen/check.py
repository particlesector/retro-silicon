"""Run every self-checking ROM in testroms/manifest.toml through MesenCE and
check it passes: a check of the reference, the ROMs and the fetch, before any
core is compared against them. ROMs with check = "frame" have no result of
their own, so they're skipped here.

usage: tools/mesen/check.py [--mesen PATH] [--roms DIR]

Needs MesenCE and xvfb-run. --roms defaults like testroms/fetch.py's --dest.
Exit codes: 0 all passed, 1 a ROM failed, 2 a ROM is missing or Mesen didn't run.
"""

import argparse
import os
import subprocess
import sys
import tempfile
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]

# blargg's older ROMs leave 1 at their result address for a pass; read it well
# after MesenCE's finish frame.
ZEROPAGE_LUA = """
-- SPDX-License-Identifier: Apache-2.0
-- Generated by tools/mesen/check.py.
local ended = 0
emu.addEventCallback(function()
  ended = ended + 1
  if ended == {frames} then
    local r = emu.read({addr}, emu.memType.nesMemory)
    print(string.format("result %d after %d frames", r, ended))
    emu.stop(r == 1 and 0 or (r == 0 and 255 or r))
  end
end, emu.eventType.endFrame)
"""


def main():
    default = os.environ.get("RS_TESTROMS", Path.home() / ".cache/retro-silicon/testroms")
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--mesen", default="Mesen")
    parser.add_argument("--roms", type=Path, default=Path(default))
    args = parser.parse_args()

    manifest = tomllib.loads((ROOT / "testroms/manifest.toml").read_text())
    blargg_lua = ROOT / "tools/mesen/blargg.lua"
    scratch = Path(tempfile.mkdtemp(prefix="rs-mesen-"))
    worst = 0
    for rom in manifest["rom"]:
        if rom["check"] == "blargg":
            lua = blargg_lua
        elif rom["check"] == "zeropage":
            lua = scratch / f"{rom['id']}.lua"
            lua.write_text(ZEROPAGE_LUA.format(frames=2 * rom["frames"] + 60, addr=rom["result"]))
        else:
            continue
        path = args.roms / rom["source"] / rom["path"]
        if not path.exists():
            print(f"MISSING {rom['id']}: {path}; run testroms/fetch.py")
            worst = 2
            continue
        try:
            p = subprocess.run(["xvfb-run", "-a", args.mesen, "--testrunner", str(path), str(lua)],
                               capture_output=True, text=True, timeout=600)
        except (OSError, subprocess.TimeoutExpired) as e:
            print(f"ERROR   {rom['id']}: {e}")
            worst = 2
            continue
        last = [l for l in p.stdout.splitlines() if l.startswith("result ") or l.startswith("no result")]
        summary = last[-1] if last else "no output"
        print(f"{'PASS' if p.returncode == 0 else 'FAIL':7} {rom['id']}: {summary}")
        if p.returncode != 0:
            worst = max(worst, 1)
    return worst


if __name__ == "__main__":
    sys.exit(main())
