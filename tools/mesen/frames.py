"""Golden frame CRCs from MesenCE, for the NES core's frames to match.

usage: tools/mesen/frames.py [--mesen PATH] [--roms DIR] [--out FILE] [--home DIR]
       tools/mesen/frames.py --dump ID FRAME [--mesen PATH] [--roms DIR] > frame.txt

For each ROM in testroms/manifest.toml with a result to check (blargg,
zeropage or frame) that needs only what the core has (see SUPPORTED), runs the
ROM in MesenCE from power-up and records the CRC-32 of a frame some time after
it finishes, in the core's pixel format: 2 bytes a pixel, low first, the PPU's
{emphasis BGR, colour}. Writes `id frames crc32 check result path` lines,
frames being how many frames have ended, so the CRC is of frame frames-1
(counting from 0), and result the zero-page address for check = "zeropage".

MesenCE runs with its own settings in --home (default ~/.cache/retro-silicon/
mesen-home): RAM and OAM zeroed at power-up, and a 512-colour palette whose
every entry encodes its own index, so its screen buffer gives the PPU's output
exactly. --dump prints one frame as rows of hex values, for tools/frame.py.

Needs MesenCE and xvfb-run.
"""

import argparse
import json
import os
import re
import subprocess
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SUPPORTED = {"cpu", "ppu"}  # what systems/nes has so far
MARGIN = 30                 # frames after MesenCE's result before the golden frame

LUA = """
-- SPDX-License-Identifier: Apache-2.0
-- Generated by tools/mesen/frames.py.
local want, dump = {want}, {dump}
local crc_table = {{}}
for i = 0, 255 do
  local c = i
  for _ = 1, 8 do
    if c & 1 == 1 then c = 0xEDB88320 ~ (c >> 1) else c = c >> 1 end
  end
  crc_table[i] = c
end
local function index(v)  -- the palette entry the pixel came from
  return ((v >> 8) & 0xFF) * 64 + (v & 0x3F)
end
local ended = 0
emu.addEventCallback(function()
  ended = ended + 1
  if ended ~= want then return end
  local b = emu.getScreenBuffer()
  local c = 0xFFFFFFFF
  for i = 1, #b do
    local p = index(b[i])
    c = crc_table[(c ~ p) & 0xFF] ~ (c >> 8)
    c = crc_table[(c ~ (p >> 8)) & 0xFF] ~ (c >> 8)
  end
  print(string.format("crc %d %08x", ended, (~c) & 0xFFFFFFFF))
  if dump then
    for y = 0, 239 do
      local row = {{}}
      for x = 0, 255 do row[#row + 1] = string.format("%03x", index(b[y * 256 + x + 1])) end
      print("row " .. y .. " " .. table.concat(row, " "))
    end
  end
  emu.stop(0)
end, emu.eventType.endFrame)
"""


def palette():
    # Entry e*64+i is red 0x10, green e, blue i: index = green*64 + (blue & 0x3F).
    return [(0x10 << 16) | (e << 8) | i for e in range(8) for i in range(64)]


def setup_home(home: Path):
    cfg = home / ".config" / "MesenCE"
    cfg.mkdir(parents=True, exist_ok=True)
    settings = cfg / "settings.json"
    want = {"Nes": {"UserPalette": palette(), "RamPowerOnState": "AllZeros"}}
    try:
        cur = json.loads(settings.read_text())
    except (OSError, ValueError):
        cur = {}
    cur.setdefault("Nes", {}).update(want["Nes"])
    settings.write_text(json.dumps(cur))


def run(mesen, home, rom: Path, frames: int, dump: bool, scratch: Path):
    lua = scratch / "frames.lua"
    lua.write_text(LUA.format(want=frames, dump="true" if dump else "false"))
    env = dict(os.environ, HOME=str(home))
    p = subprocess.run(["xvfb-run", "-a", mesen, "--testrunner", str(rom), str(lua)],
                       capture_output=True, text=True, timeout=900, env=env)
    return p.stdout


def main():
    default_roms = os.environ.get("RS_TESTROMS", Path.home() / ".cache/retro-silicon/testroms")
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--mesen", default="Mesen")
    ap.add_argument("--roms", type=Path, default=Path(default_roms))
    ap.add_argument("--out", type=Path, default=ROOT / "harness/golden/nes_frames_crc32.txt")
    ap.add_argument("--home", type=Path, default=Path.home() / ".cache/retro-silicon/mesen-home")
    ap.add_argument("--dump", nargs=2, metavar=("ID", "FRAME"))
    args = ap.parse_args()

    manifest = tomllib.loads((ROOT / "testroms/manifest.toml").read_text())
    roms = {r["id"]: r for r in manifest["rom"]}
    setup_home(args.home)
    scratch = args.home / "scratch"
    scratch.mkdir(exist_ok=True)

    if args.dump:
        rid, frame = args.dump
        r = roms[rid]
        out = run(args.mesen, args.home, args.roms / r["source"] / r["path"], int(frame) + 1, True, scratch)
        for line in out.splitlines():
            if line.startswith("row "):
                print(line[4:].split(" ", 1)[1])
        return 0

    lines = ["# Golden frame CRCs from MesenCE: id, frames ended, CRC-32 of the last, check, result, path.",
             "# Generated by tools/mesen/frames.py; don't edit by hand."]
    worst = 0
    for r in manifest["rom"]:
        needs = {n.strip() for n in r["needs"].split(",")}
        if r["check"] not in ("blargg", "zeropage", "frame") or not needs <= SUPPORTED:
            continue
        path = args.roms / r["source"] / r["path"]
        if not path.exists():
            print(f"MISSING {r['id']}: {path}; run testroms/fetch.py", file=sys.stderr)
            worst = 2
            continue
        head = path.read_bytes()[:16]
        if (head[6] >> 4) | (head[7] & 0xF0):
            continue  # systems/nes has NROM (mapper 0) only so far
        frames = r["frames"] + MARGIN
        out = run(args.mesen, args.home, path, frames, False, scratch)
        m = re.search(r"^crc (\d+) ([0-9a-f]{8})$", out, re.M)
        if not m or int(m.group(1)) != frames:
            print(f"ERROR   {r['id']}: no CRC from MesenCE", file=sys.stderr)
            worst = 2
            continue
        print(f"{r['id']}: frame {frames - 1} 0x{m.group(2)}")
        result = f"0x{r['result']:02x}" if r["check"] == "zeropage" else "-"
        lines.append(f"{r['id']} {frames} 0x{m.group(2)} {r['check']} {result} {r['path']}")
    args.out.write_text("\n".join(lines) + "\n")
    return worst


if __name__ == "__main__":
    sys.exit(main())
